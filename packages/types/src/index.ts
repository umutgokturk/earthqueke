/** A single normalized report as returned by a provider adapter. */
export interface EarthquakeReport {
  /** Stable id within the provider adapter (source-scoped). */
  id: string;
  source: SourceId;
  /** The provider's own event id when it exposes one. */
  sourceEventId?: string;
  /** UTC ISO timestamp of the event origin time. */
  occurredAt: string;
  latitude: number;
  longitude: number;
  depthKm: number;
  magnitude: number;
  magnitudeType?: string;
  location: string;
  dataClass?: DataClass;
  rawPayload?: unknown;
}

