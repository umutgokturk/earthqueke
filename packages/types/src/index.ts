// ─────────────────────────────────────────────────────────────
// Helpers
// ─────────────────────────────────────────────────────────────

export function rangeToMs(range: TimeRange): number {
  switch (range) {
    case '1h':
      return 3_600_000;
    case '6h':
      return 21_600_000;
    case '24h':
      return 86_400_000;
    case '7d':
      return 7 * 86_400_000;
    case '30d':
      return 30 * 86_400_000;
  }
}

/** Recommended aggregation bucket (ms) per requested range — backend-side aggregation. */
export function bucketForRange(range: TimeRange): number {
  switch (range) {
    case '1h':
      return 5 * 60_000;
    case '6h':
      return 15 * 60_000;
    case '24h':
      return 3_600_000;
    case '7d':
      return 6 * 3_600_000;
    case '30d':
      return 24 * 3_600_000;
  }
}
