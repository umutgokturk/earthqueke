// ─────────────────────────────────────────────────────────────
// Sources & data classes
// ─────────────────────────────────────────────────────────────

/** Upstream data providers. MOCK exists only outside production and is always labelled. */
export type SourceId = 'AFAD' | 'KANDILLI' | 'MOCK' | 'OTHER';

export const SOURCE_IDS: SourceId[] = ['AFAD', 'KANDILLI', 'MOCK', 'OTHER'];

/**
 * Provenance class of a stored record:
 *  - live : ingested from a real upstream provider
 *  - seed : synthetic history created by `db:seed` (development only)
 *  - mock : generated by the mock development provider
 * Anything other than `live` must be visually labelled in the UI.
 */
export type DataClass = 'live' | 'seed' | 'mock';

export type SourceHealth = 'ONLINE' | 'DEGRADED' | 'OFFLINE' | 'DISABLED' | 'UNKNOWN';

// ─────────────────────────────────────────────────────────────
// GeoJSON (minimal structural types, RFC 7946 compatible)
// ─────────────────────────────────────────────────────────────

export type Position = [longitude: number, latitude: number];

export interface PointGeometry {
  type: 'Point';
  coordinates: Position;
}
export interface LineStringGeometry {
  type: 'LineString';
  coordinates: Position[];
}
export interface MultiLineStringGeometry {
  type: 'MultiLineString';
  coordinates: Position[][];
}
export interface PolygonGeometry {
  type: 'Polygon';
  coordinates: Position[][];
}
export type Geometry =
  | PointGeometry
  | LineStringGeometry
  | MultiLineStringGeometry
  | PolygonGeometry;

export interface Feature<G extends Geometry = Geometry, P = Record<string, unknown>> {
  type: 'Feature';
  geometry: G;
  properties: P;
  id?: string | number;
}
export interface FeatureCollection<G extends Geometry = Geometry, P = Record<string, unknown>> {
  type: 'FeatureCollection';
  features: Feature<G, P>[];
}

