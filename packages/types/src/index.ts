// ─────────────────────────────────────────────────────────────
// Activity index (NOT a prediction)
// ─────────────────────────────────────────────────────────────

export type ActivityLevel = 'LOW' | 'MODERATE' | 'ELEVATED' | 'HIGH' | 'VERY_HIGH';

export interface ActivityComponents {
  frequency: number;
  magnitude: number;
  recency: number;
  clustering: number;
  depth: number;
}

export interface ActivitySnapshot {
  region: string;
  score: number;
  level: ActivityLevel;
  components: ActivityComponents;
  computedAt: string;
  windowHours: number;
  sampleSize: number;
  /** Mandatory disclaimer, surfaced verbatim in the UI. */
  disclaimer: string;
}

export const ACTIVITY_DISCLAIMER =
  'Bu değer deprem tahmini değildir. Yalnızca gözlenen geçmiş ve mevcut verinin istatistiksel yoğunluğunu gösterir.';

export function activityLevelForScore(score: number): ActivityLevel {
  if (score < 20) return 'LOW';
  if (score < 40) return 'MODERATE';
  if (score < 60) return 'ELEVATED';
  if (score < 80) return 'HIGH';
  return 'VERY_HIGH';
}

